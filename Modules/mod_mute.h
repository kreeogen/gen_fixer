/*******************************************************************************
 * mod_mute.h
 * * MUTE HOTKEY MODULE HEADER
 * ЗАГОЛОВОК МОДУЛЯ ГОРЯЧЕЙ КЛАВИШИ MUTE
 * * PURPOSE / НАЗНАЧЕНИЕ:
 * Adds a global "Mute" hotkey (Ctrl+Space) to Winamp 2.95, which lacks this
 * function natively.
 * * Добавляет глобальную горячую клавишу "Mute" (Ctrl+Пробел) в Winamp 2.95,
 * где эта функция отсутствует нативно.
 ******************************************************************************/

#pragma once
#include "..\Resources\plugin_common.h"

/*******************************************************************************
 * Mute_Init
 * * PURPOSE / НАЗНАЧЕНИЕ:
 * Subclasses the main Winamp window to intercept keyboard input (Ctrl+Space).
 * Сабклассит (перехватывает сообщения) главного окна Winamp для перехвата
 * ввода с клавиатуры (Ctrl+Пробел).
 ******************************************************************************/
void Mute_Init(void);

/*******************************************************************************
 * Mute_Quit
 * * PURPOSE / НАЗНАЧЕНИЕ:
 * Removes the window subclass and restores original input handling.
 * Удаляет сабклассинг окна и восстанавливает оригинальную обработку ввода.
 ******************************************************************************/
void Mute_Quit(void);